const bits = Buffer.from(SQUARES, "base64");

/** How many squares the list holds. */
export const COPERNICUS_SQUARE_COUNT = 26450;

/** True when Copernicus has a file for the degree square this place is in. */
export function copernicusHasSquare(lat: number, lng: number): boolean {
  const la = Math.floor(lat);
  const lo = Math.floor(lng);
  if (la < -90 || la > 89 || lo < -180 || lo > 179) return false;
  const i = (la + 90) * 360 + (lo + 180);
  return ((bits[i >> 3] ?? 0) & (1 << (i & 7))) !== 0;
}
